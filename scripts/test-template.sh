        required timeout "devcontainer config check" || fail=1
    else
        for cfg in .devcontainer/devcontainer.json .devcontainer/dev/devcontainer.json; do
            [ -f "$cfg" ] || continue
            "$timeout_bin" -k 5 60 devcontainer read-configuration \
                --docker-path true \
